import { useEffect, useMemo, useState, type FormEvent } from 'react';
import { api, ApiError } from '../lib/api';
import type { BookingResult, Doctor, Page, Slot } from '../types';
import { ErrorNote, fmtDateTime, fmtMoney, Spinner } from './ui';

/** How far ahead a doctor's open slots are fetched. */
const BOOKING_WINDOW_DAYS = 30;

function availabilityWindow(): { from: string; to: string } {
  const from = new Date();
  const to = new Date();
  to.setDate(to.getDate() + BOOKING_WINDOW_DAYS);
  return { from: from.toISOString(), to: to.toISOString() };
}

interface BookingFlowProps {
  /** Called after a successful booking so the parent can refresh lists. */
  onBooked?: (result: BookingResult) => void;
  /** Doctors to choose from; when omitted a listing is loaded internally. */
  doctors?: Doctor[];
}

/**
 * The 3-step patient booking flow: pick a doctor, pick an available slot,
 * confirm. Confirm POSTs /api/v1/consultations/booking with an
 * X-Idempotency-Key generated by the API layer; a repeated confirm replays
 * the stored booking instead of creating a duplicate.
 *
 * The steps are gated with an `interacting` flag instead of
 * `fieldset[disabled]`: a disabled fieldset swallows pointer events on its
 * children, which would block the click on a slot radio the moment the
 * previous step became active.
 */
export function BookingFlow({ onBooked, doctors }: BookingFlowProps): JSX.Element {
  const [doctorsLoaded, setDoctorsLoaded] = useState<Doctor[] | null>(null);
  const [doctorsError, setDoctorsError] = useState<string | null>(null);
  const [selectedDoctor, setSelectedDoctor] = useState<Doctor | null>(null);
  const [slots, setSlots] = useState<Slot[] | null>(null);
  const [slotsLoading, setSlotsLoading] = useState(false);
  const [slotsError, setSlotsError] = useState<string | null>(null);
  const [selectedSlot, setSelectedSlot] = useState<Slot | null>(null);
  const [booking, setBooking] = useState(false);
  const [bookingError, setBookingError] = useState<string | null>(null);
  const [result, setResult] = useState<BookingResult | null>(null);


  const doctorList = doctors ?? doctorsLoaded;

  useEffect(() => {
    if (doctors !== undefined || doctorsLoaded !== null) {
      return;
    }
    let cancelled = false;
    setDoctorsError(null);
    api<Page<Doctor>>('/api/v1/doctors', {
      query: { page: 0, size: 50 }
    })
      .then((page) => {
        if (!cancelled) setDoctorsLoaded(page.content);
      })
      .catch((err: unknown) => {
        if (!cancelled) {
          setDoctorsError(err instanceof ApiError ? err.message : 'Failed to load doctors');
        }
      });
    return () => {
      cancelled = true;
    };
  }, [doctors, doctorsLoaded]);

  const openSlots = useMemo(
    () => (slots === null ? [] : slots.filter((s) => s.status === 'AVAILABLE')),
    [slots]
  );

  const loadSlots = async (doctor: Doctor): Promise<void> => {
    setSlotsLoading(true);
    setSlotsError(null);
    setSelectedSlot(null);
    setBookingError(null);
    setResult(null);
    try {
      const { from, to } = availabilityWindow();
      const page = await api<Page<Slot>>(`/api/v1/doctors/${doctor.id}/availability`, {
        query: { from, to, page: 0, size: 50 }
      });
      setSlots(page.content);
    } catch (err) {
      setSlots([]);
      setSlotsError(err instanceof ApiError ? err.message : 'Failed to load available slots');
    } finally {
      setSlotsLoading(false);
    }
  };

  const pickDoctor = (doctor: Doctor): void => {
    setSelectedDoctor(doctor);
    setSelectedSlot(null);
    void loadSlots(doctor);
  };

  const pickSlot = (slot: Slot): void => {
    setSelectedSlot(slot);
  };

  const confirm = async (e: FormEvent<HTMLFormElement>): Promise<void> => {
    e.preventDefault();
    if (selectedDoctor === null || selectedSlot === null) {
      return;
    }
    setBooking(true);
    setBookingError(null);
    try {
      // The API layer attaches the X-Idempotency-Key header automatically.
      const booked = await api<BookingResult>('/api/v1/consultations/booking', {
        method: 'POST',
        body: {
          doctorId: selectedDoctor.id,
          slotId: selectedSlot.id,
          paymentMethod: 'card'
        }
      });
      setResult(booked);
      onBooked?.(booked);
    } catch (err) {
      setBookingError(err instanceof ApiError ? err.message : 'Booking failed. Please try again.');
    } finally {
      setBooking(false);
    }
  };

  if (result !== null) {
    return (
      <div className="booking-success" data-testid="booking-success">
        <h3>Consultation {result.replayed ? 'replayed' : 'booked'}</h3>
        <p>
          Consultation <code>{result.consultationId}</code> with payment{' '}
          <code>{result.paymentId}</code> — status {result.status}.
        </p>
        <button
          type="button"
          className="btn btn--ghost"
          onClick={() => {
            setResult(null);
            setSelectedDoctor(null);
            setSelectedSlot(null);
            setSlots(null);
          }}
        >
          Book another
        </button>
      </div>
    );
  }

  const confirmDisabled = selectedSlot === null || booking;

  return (
    <form className="booking-flow" onSubmit={confirm} data-testid="booking-form">
      <section className="booking-step">
        <h3 className="booking-step__legend">1 · Choose a doctor</h3>
        {doctorsError !== null ? <ErrorNote error={doctorsError} /> : null}
        {doctors === undefined && doctorsLoaded === null && doctorsError === null ? (
          <Spinner label="Loading doctors…" />
        ) : (
          <div className="booking-doctor-list" role="radiogroup" aria-label="Doctors">
            {(doctorList ?? []).map((d) => (
              <label
                key={d.id}
                className={
                  'booking-doctor' +
                  (selectedDoctor?.id === d.id ? ' booking-doctor--selected' : '')
                }
              >
                <input
                  type="radio"
                  name="doctor"
                  checked={selectedDoctor?.id === d.id}
                  onChange={() => pickDoctor(d)}
                  aria-label={d.name}
                />
                <span className="booking-doctor__name">{d.name}</span>
                <span className="booking-doctor__meta">
                  {d.specialization} · {fmtMoney(d.consultationFee)} · ★ {d.ratings.toFixed(1)} ({d.totalRatings})
                </span>
              </label>
            ))}
            {(doctorList ?? []).length === 0 ? (
              <p className="muted">No doctors available.</p>
            ) : null}
          </div>
        )}
      </section>

      <section className="booking-step">
        <h3 className="booking-step__legend">2 · Pick a slot</h3>
        {selectedDoctor === null ? (
          <p className="muted">Select a doctor first.</p>
        ) : slotsLoading ? (
          <Spinner label="Loading slots…" />
        ) : slotsError !== null ? (
          <ErrorNote error={slotsError} onRetry={() => void loadSlots(selectedDoctor)} />
        ) : openSlots.length === 0 ? (
          <p className="muted">No open slots in the next {BOOKING_WINDOW_DAYS} days.</p>
        ) : (
          <div className="slot-list" role="radiogroup" aria-label="Slots">
            {openSlots.map((s) => (
              <label
                key={s.id}
                className={'slot-chip' + (selectedSlot?.id === s.id ? ' slot-chip--selected' : '')}
              >
                <input
                  type="radio"
                  name="slot"
                  checked={selectedSlot?.id === s.id}
                  onChange={() => pickSlot(s)}
                  aria-label={`${fmtDateTime(s.startAt)} to ${fmtDateTime(s.endAt)}`}
                />
                {fmtDateTime(s.startAt)} – {fmtDateTime(s.endAt)}
              </label>
            ))}
          </div>
        )}
      </section>

      <section className="booking-step">
        <h3 className="booking-step__legend">3 · Confirm</h3>
        {bookingError !== null ? <ErrorNote error={bookingError} /> : null}
        <div className="booking-confirm">
          <button
            type="submit"
            className="btn btn--primary"
            disabled={confirmDisabled}
          >
            {booking ? 'Booking…' : 'Confirm booking'}
          </button>
          <p className="muted">
            Booking creates a consultation and a payment in one idempotent step.
          </p>
        </div>
      </section>
    </form>
  );
}
